#include <iostream>
#include <vector>
#include <random>
#include <chrono>
#include <cmath>
#include <iomanip>

// Dynamic Types based on compilation flags injected by the bash script
#if TYPE_IN == 16
using T_in = _Float16;
#elif TYPE_IN == 32
using T_in = float;
#else
using T_in = double;
#endif

#if TYPE_OUT == 16
using T_out = _Float16;
#elif TYPE_OUT == 32
using T_out = float;
#else
using T_out = double;
#endif

// MLIR ABI MemRefs
template<typename T> struct MemRef0D { T* basePtr; T* data; int64_t offset; };
template<typename T> struct MemRef1D { T* basePtr; T* data; int64_t offset; int64_t sizes[1]; int64_t strides[1]; };
template<typename T> struct MemRef2D { T* basePtr; T* data; int64_t offset; int64_t sizes[2]; int64_t strides[2]; };

// External MLIR Function generated by the MLIR pipeline
extern "C" void MLIR_CIFACE_FUNC(
    int64_t m, int64_t n, int64_t k,
    MemRef0D<T_out>* alpha,
    MemRef2D<T_in>* a,
    MemRef2D<T_in>* b,
    MemRef0D<T_out>* beta,
    MemRef1D<T_out>* c,
    int64_t rs_c, int64_t cs_c,
    int64_t data, int64_t cntx
);

// Naive C++ Ground Truth (Perfectly matches edge cases and padding)
void naive_ukernel(int64_t m, int64_t n, int64_t k, T_out alpha, T_in* A, T_in* B, T_out beta, T_out* C, int64_t rs_c, int64_t cs_c) {
    for (int64_t i = 0; i < m; ++i) {
        for (int64_t j = 0; j < n; ++j) {
            T_out sum = 0;
            for (int64_t p = 0; p < k; ++p) {
                // A is contiguous blocks of size TEST_MR, B is contiguous blocks of size TEST_NR
                sum += (T_out)A[p * TEST_MR + i] * (T_out)B[p * TEST_NR + j];
            }
            C[i * rs_c + j * cs_c] = alpha * sum + beta * C[i * rs_c + j * cs_c];
        }
    }
}

int main(int argc, char** argv) {
    if (argc < 5) {
        std::cerr << "Usage: ./test_ukernel <m> <n> <k> <iterations>\n";
        return 1;
    }

    int64_t m = std::stoll(argv[1]);
    int64_t n = std::stoll(argv[2]);
    int64_t k = std::stoll(argv[3]);
    int iterations = std::stoi(argv[4]);

    // Set striding based on layout
    int64_t rs_c = 1;
    int64_t cs_c = TEST_MR; // Default Column Major
    #ifdef IS_ROW_MAJOR
        rs_c = TEST_NR;
        cs_c = 1;
    #endif

    // Allocate Memory (Padded to TEST_MR and TEST_NR like BLIS expects internally)
    std::vector<T_in> A(TEST_MR * k);
    std::vector<T_in> B(TEST_NR * k);
    std::vector<T_out> C_mlir(TEST_MR * TEST_NR * 2, 0); // Extra padding for boundary safety
    std::vector<T_out> C_naive(TEST_MR * TEST_NR * 2, 0);

    // Initialize with small random numbers to prevent precision drift / overflow
    std::random_device rd;
    std::mt19937 gen(rd());
    std::uniform_real_distribution<float> dist(-1.0f, 1.0f);

    for (auto& val : A) val = (T_in)dist(gen);
    for (auto& val : B) val = (T_in)dist(gen);

    T_out alpha = (T_out)1.0f;
    T_out beta = (T_out)0.0f;

    MemRef0D<T_out> mr_alpha = {&alpha, &alpha, 0};
    MemRef0D<T_out> mr_beta  = {&beta, &beta, 0};
    MemRef2D<T_in> mr_A = { A.data(), A.data(), 0, {k, TEST_MR}, {TEST_MR, 1} };
    MemRef2D<T_in> mr_B = { B.data(), B.data(), 0, {k, TEST_NR}, {TEST_NR, 1} };
    MemRef1D<T_out> mr_C = { C_mlir.data(), C_mlir.data(), 0, {TEST_MR * TEST_NR * 2}, {1} };

    // --- Benchmark MLIR Kernel ---
    auto start = std::chrono::high_resolution_clock::now();
    for (int i = 0; i < iterations; ++i) {
        MLIR_CIFACE_FUNC(m, n, k, &mr_alpha, &mr_A, &mr_B, &mr_beta, &mr_C, rs_c, cs_c, 0, 0);
    }
    auto end = std::chrono::high_resolution_clock::now();
    
    std::chrono::duration<double> diff = end - start;
    double gflops = (2.0 * m * n * k * iterations) / (diff.count() * 1e9);

    // --- Check correctness against Naive C++ ---
    naive_ukernel(m, n, k, alpha, A.data(), B.data(), beta, C_naive.data(), rs_c, cs_c);

    float max_diff = 0;
    for (int i = 0; i < m; ++i) {
        for (int j = 0; j < n; ++j) {
            float val_mlir = (float)C_mlir[i * rs_c + j * cs_c];
            float val_naive = (float)C_naive[i * rs_c + j * cs_c];
            max_diff = std::max(max_diff, std::abs(val_mlir - val_naive));
        }
    }

    std::cout << "Benchmarking Micro-Kernel: " << m << "x" << n << "x" << k << "\n";
    std::cout << "Max difference vs Naive: " << max_diff << "\n";
    std::cout << "MLIR Performance: " << gflops << " GFLOPS\n";

    if (max_diff < 1e-2) std::cout << "Result check: PASSED\n";
    else std::cout << "Result check: FAILED\n";

    return 0;
}

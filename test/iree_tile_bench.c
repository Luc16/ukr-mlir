// Tile-level comparison of ukr-mlir micro-kernels against IREE's arm64 f32
// mmt4d tile functions (plan.md, "Level 1").
//
// Every kernel runs inside the same outer M1 x N1 loop (a copy of IREE's
// iree_uk_mmt4d_using_tile_func, prefetches included) and is called through a
// function pointer with IREE's tile-function signature. Current ukr-mlir
// kernels ("ukr") are called through their bare-pointer entry
// <name>_tile(out, lhs, rhs, K); the first version ("ukr-v1": MLIR C interface,
// no K split) and the BLIS-style kernel go through a shim that builds their
// memref descriptors.
//
// Data layout (f32, K0 = 1): LHS panel [K][M0], RHS panel [K][N0], output tile
// M0 x N0 row-major. IREE's ACCUMULATE flag maps to the ukr-mlir beta = 1
// kernel, no flag to the beta = 0 kernel.
//
// Build and run through scripts/iree_tile_bench.sh. Results go to stdout as CSV.

#include <arm_neon.h>
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#ifdef __APPLE__
#include <pthread/qos.h>
#endif

#include "iree/builtins/ukernel/mmt4d_internal.h"


#define NUM_KERNELS ((int)(sizeof(kKernels) / sizeof(kKernels[0])))

// ------------------------------------------------------------
// Outer loop: copy of iree_uk_mmt4d_using_tile_func (mmt4d.c), f32 only.
// ------------------------------------------------------------
static void run_mmt4d(const iree_uk_mmt4d_params_t *p,
                      iree_uk_mmt4d_tile_func_t tile_func) {
  float *out_tile_row = (float *)p->out_buffer + p->out_offset;
  const float *lhs_panel = (const float *)p->lhs_buffer + p->lhs_offset;
  const float *rhs_panel_start = (const float *)p->rhs_buffer + p->rhs_offset;
  const int out_tile_size = p->M0 * p->N0;
  for (iree_uk_index_t i = 0; i < p->M; ++i) {
    float *out_tile = out_tile_row;
    const float *rhs_panel = rhs_panel_start;
    IREE_UK_PREFETCH_RW(out_tile_row, IREE_UK_PREFETCH_LOCALITY_L3);
    IREE_UK_PREFETCH_RO(lhs_panel, IREE_UK_PREFETCH_LOCALITY_L1);
    IREE_UK_PREFETCH_RO(rhs_panel, IREE_UK_PREFETCH_LOCALITY_L1);
    for (iree_uk_index_t j = 0; j < p->N; ++j) {
      tile_func(out_tile, lhs_panel, rhs_panel, p);
      out_tile += out_tile_size;
      rhs_panel += p->rhs_stride0;
    }
    out_tile_row += p->out_stride0;
    lhs_panel += p->lhs_stride0;
  }
}

static iree_uk_mmt4d_params_t make_params(const kernel_t *k, int M1, int N1,
                                          int K, int accumulate, float *lhs,
                                          float *rhs, float *out) {
  iree_uk_mmt4d_params_t p = {0};
  p.lhs_buffer = lhs;
  p.lhs_stride0 = (iree_uk_index_t)K * k->M0;
  p.rhs_buffer = rhs;
  p.rhs_stride0 = (iree_uk_index_t)K * k->N0;
  p.out_buffer = out;
  p.out_stride0 = (iree_uk_index_t)N1 * k->M0 * k->N0;
  p.M = M1;
  p.N = N1;
  p.K = K;
  p.M0 = k->M0;
  p.N0 = k->N0;
  p.K0 = 1;
  p.flags = IREE_UK_FLAG_MMT4D_TYPE_F32F32F32 |
            (accumulate ? IREE_UK_FLAG_MMT4D_ACCUMULATE : 0);
  return p;
}

// ------------------------------------------------------------
// Correctness: small integer values so every sum is exact in f32.
// With accumulate off the output starts as NaN, so a kernel that reads it fails.
// ------------------------------------------------------------
static int check_kernel(const kernel_t *k, int K, int accumulate) {
  const int M1 = 2, N1 = 3, M0 = k->M0, N0 = k->N0;
  size_t nl = (size_t)M1 * K * M0, nr = (size_t)N1 * K * N0,
         no = (size_t)M1 * N1 * M0 * N0;
  float *lhs = malloc(nl * sizeof(float)), *rhs = malloc(nr * sizeof(float));
  float *out = malloc(no * sizeof(float)), *ref = malloc(no * sizeof(float));
  for (size_t i = 0; i < nl; i++) lhs[i] = (float)((int)(i * 7 % 9) - 4);
  for (size_t i = 0; i < nr; i++) rhs[i] = (float)((int)(i * 5 % 9) - 4);
  for (size_t i = 0; i < no; i++) {
    out[i] = accumulate ? (float)((int)(i % 13) - 6) : NAN;
    ref[i] = accumulate ? out[i] : 0.0f;
  }
  for (int i1 = 0; i1 < M1; i1++)
    for (int j1 = 0; j1 < N1; j1++)
      for (int i = 0; i < M0; i++)
        for (int j = 0; j < N0; j++) {
          float s = 0;
          for (int kk = 0; kk < K; kk++)
            s += lhs[((size_t)i1 * K + kk) * M0 + i] *
                 rhs[((size_t)j1 * K + kk) * N0 + j];
          ref[((size_t)(i1 * N1 + j1) * M0 + i) * N0 + j] += s;
        }
  iree_uk_mmt4d_params_t p = make_params(k, M1, N1, K, accumulate, lhs, rhs, out);
  run_mmt4d(&p, k->fn);
  int bad = 0;
  for (size_t i = 0; i < no; i++) bad += !(out[i] == ref[i]);
  if (bad)
    fprintf(stderr, "FAIL %s %dx%d K=%d acc=%d: %d/%zu wrong elements\n",
            k->impl, M0, N0, K, accumulate, bad, no);
  free(lhs); free(rhs); free(out); free(ref);
  return bad != 0;
}

// ------------------------------------------------------------
// Timing
// ------------------------------------------------------------
static double now_ns(void) {
  struct timespec ts;
  clock_gettime(CLOCK_MONOTONIC_RAW, &ts);
  return ts.tv_sec * 1e9 + ts.tv_nsec;
}

static int cmp_double(const void *a, const void *b) {
  double x = *(const double *)a, y = *(const double *)b;
  return (x > y) - (x < y);
}

// NEON FMA throughput: 20 independent accumulators hide the FMA latency.
// The multiplicands rotate over 2 x 2 registers: on Apple M4, FMAs that all
// share the same two source registers do not reach full throughput.
// The volatile seed stops clang from rematerializing the constant operands
// with DUPs inside the loop, which would compete with the FMAs for the pipes.
#define PEAK_ACCS 20
static double measure_peak_gflops(double seconds) {
  static volatile float seed = 1e-3f;
  float32x4_t acc[PEAK_ACCS], a[2], b[2];
  for (int i = 0; i < PEAK_ACCS; i++) acc[i] = vdupq_n_f32((float)i);
  for (int i = 0; i < 2; i++) {
    a[i] = vdupq_n_f32(1.0f - seed * (i + 1));
    b[i] = vdupq_n_f32(seed * (i + 1));
  }
  const long inner = 1 << 16;
  long iters = 0;
  double t0 = now_ns(), t1;
  do {
    for (long it = 0; it < inner; it++) {
#pragma clang loop unroll(full)
      for (int i = 0; i < PEAK_ACCS; i++)
        acc[i] = vfmaq_f32(acc[i], a[i & 1], b[(i >> 1) & 1]);
    }
    iters += inner;
    t1 = now_ns();
  } while (t1 - t0 < seconds * 1e9);
  float32x4_t s = acc[0];
  for (int i = 1; i < PEAK_ACCS; i++) s = vaddq_f32(s, acc[i]);
  volatile float sink = vaddvq_f32(s);
  (void)sink;
  return (double)iters * PEAK_ACCS * 4 * 2 / (t1 - t0);
}

// A benchmark case: the same (K, mode, accumulate) for every kernel.
// Modes:
//   hot  - one tile (M1 = N1 = 1) called repeatedly: operands stay in L1.
//   warm - one M1 x N1 = 8 x 8 problem called repeatedly: mostly L1/L2.
//   cold - cycle through 8 x 8 problems spread over a large arena, so every
//          call starts with its panels out of cache.
typedef struct {
  const char *mode;
  int M1, N1;
} bench_mode_t;

static const bench_mode_t kModes[] = {{"hot", 1, 1}, {"warm", 8, 8}, {"cold", 8, 8}};

typedef struct {
  const kernel_t *k;
  int nprob;
  size_t lhs_n, rhs_n, out_n, prob_n;  // floats
  long calls_per_sample;
  double *samples;  // GFLOP/s
} run_t;

static float *g_arena;
static size_t g_arena_n;  // floats

static iree_uk_mmt4d_params_t problem_params(const run_t *r, const bench_mode_t *m,
                                             int K, int acc, int idx) {
  float *base = g_arena + (size_t)idx * r->prob_n;
  return make_params(r->k, m->M1, m->N1, K, acc, base, base + r->lhs_n,
                     base + r->lhs_n + r->rhs_n);
}

static double time_calls(run_t *r, const bench_mode_t *m, int K, int acc,
                         long calls, int *next) {
  double t0 = now_ns();
  for (long c = 0; c < calls; c++) {
    iree_uk_mmt4d_params_t p = problem_params(r, m, K, acc, *next);
    run_mmt4d(&p, r->k->fn);
    if (++*next == r->nprob) *next = 0;
  }
  return now_ns() - t0;
}

static void usage(const char *argv0) {
  fprintf(stderr,
          "Usage: %s [--k=64,256,1024] [--modes=hot,warm,cold] [--reps=15]\n"
          "          [--sample-ms=20] [--arena-mb=256] [--check-only]\n",
          argv0);
  exit(1);
}

static int parse_list(const char *s, int *out, int max) {
  int n = 0;
  while (*s && n < max) {
    out[n++] = atoi(s);
    while (*s && *s != ',') s++;
    if (*s == ',') s++;
  }
  return n;
}

int main(int argc, char **argv) {
  int ks[16] = {64, 256, 1024}, nk = 3;
  const char *modes = "hot,warm,cold";
  int reps = 15, warmup_reps = 2, check_only = 0;
  double sample_ms = 20;
  size_t arena_mb = 256;
  for (int i = 1; i < argc; i++) {
    if (!strncmp(argv[i], "--k=", 4)) nk = parse_list(argv[i] + 4, ks, 16);
    else if (!strncmp(argv[i], "--modes=", 8)) modes = argv[i] + 8;
    else if (!strncmp(argv[i], "--reps=", 7)) reps = atoi(argv[i] + 7);
    else if (!strncmp(argv[i], "--sample-ms=", 12)) sample_ms = atof(argv[i] + 12);
    else if (!strncmp(argv[i], "--arena-mb=", 11)) arena_mb = atol(argv[i] + 11);
    else if (!strcmp(argv[i], "--check-only")) check_only = 1;
    else usage(argv[0]);
  }

#ifdef __APPLE__
  // macOS cannot pin threads; the highest QoS keeps us on a performance core.
  pthread_set_qos_class_self_np(QOS_CLASS_USER_INTERACTIVE, 0);
#endif

  int fails = 0;
  for (int i = 0; i < NUM_KERNELS; i++)
    for (int acc = 0; acc <= 1; acc++) {
      fails += check_kernel(&kKernels[i], 37, acc);
      for (int ki = 0; ki < nk; ki++) fails += check_kernel(&kKernels[i], ks[ki], acc);
    }
  if (fails) {
    fprintf(stderr, "%d correctness failures, not benchmarking.\n", fails);
    return 1;
  }
  fprintf(stderr, "correctness: all %d kernels ok\n", NUM_KERNELS);
  if (check_only) return 0;

  measure_peak_gflops(0.3);  // ramp the clock up
  double peak = measure_peak_gflops(0.5);
  fprintf(stderr, "measured NEON f32 FMA peak: %.1f GFLOP/s\n", peak);

  g_arena_n = arena_mb << 18;
  g_arena = aligned_alloc(64, g_arena_n * sizeof(float));
  for (size_t i = 0; i < g_arena_n; i++) g_arena[i] = (float)((int)(i % 7) - 3) * 0.125f;

  printf("impl,M0,N0,K,accumulate,mode,M1,N1,median_gflops,min_gflops,"
         "max_gflops,mad_pct,peak_pct,peak_gflops\n");

  run_t runs[NUM_KERNELS];
  for (size_t mi = 0; mi < sizeof(kModes) / sizeof(kModes[0]); mi++) {
    const bench_mode_t *m = &kModes[mi];
    if (!strstr(modes, m->mode)) continue;
    for (int ki = 0; ki < nk; ki++) {
      int K = ks[ki];
      for (int acc = 0; acc <= 1; acc++) {
        // Calibrate each kernel so one sample takes about sample_ms.
        for (int i = 0; i < NUM_KERNELS; i++) {
          run_t *r = &runs[i];
          r->k = &kKernels[i];
          r->lhs_n = (size_t)m->M1 * K * r->k->M0;
          r->rhs_n = (size_t)m->N1 * K * r->k->N0;
          r->out_n = (size_t)m->M1 * m->N1 * r->k->M0 * r->k->N0;
          r->prob_n = (r->lhs_n + r->rhs_n + r->out_n + 15) & ~(size_t)15;
          r->nprob = strcmp(m->mode, "cold") ? 1 : (int)(g_arena_n / r->prob_n);
          int next = 0;
          long calls = 1;
          double t;
          while ((t = time_calls(r, m, K, acc, calls, &next)) < sample_ms * 1e6 / 4)
            calls *= 2;
          r->calls_per_sample = (long)(calls * sample_ms * 1e6 / t) + 1;
          r->samples = malloc(sizeof(double) * reps);
        }
        // Round-robin samples so clock or thermal drift hits every kernel alike.
        int next[NUM_KERNELS] = {0};
        for (int s = -warmup_reps; s < reps; s++)
          for (int i = 0; i < NUM_KERNELS; i++) {
            run_t *r = &runs[i];
            double t = time_calls(r, m, K, acc, r->calls_per_sample, &next[i]);
            double flops = 2.0 * r->k->M0 * r->k->N0 * K * m->M1 * m->N1 *
                           r->calls_per_sample;
            if (s >= 0) r->samples[s] = flops / t;
          }
        for (int i = 0; i < NUM_KERNELS; i++) {
          run_t *r = &runs[i];
          double *v = r->samples, dev[256];
          qsort(v, reps, sizeof(double), cmp_double);
          double med = v[reps / 2];
          for (int s = 0; s < reps && s < 256; s++) dev[s] = fabs(v[s] - med);
          qsort(dev, reps < 256 ? reps : 256, sizeof(double), cmp_double);
          printf("%s,%d,%d,%d,%d,%s,%d,%d,%.2f,%.2f,%.2f,%.2f,%.1f,%.1f\n",
                 r->k->impl, r->k->M0, r->k->N0, K, acc, m->mode, m->M1, m->N1,
                 med, v[0], v[reps - 1], 100.0 * dev[reps / 2] / med,
                 100.0 * med / peak, peak);
          fflush(stdout);
          free(r->samples);
        }
      }
    }
  }
  free(g_arena);
  return 0;
}
